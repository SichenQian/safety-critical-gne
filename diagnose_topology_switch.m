function V=diagnose_topology_switch(source,outDir)
%DIAGNOSE_TOPOLOGY_SWITCH Read-only diagnostics of the existing paper runs.
% No integration, controller switch, state reset, graph threshold, or figure.
% Geometric cutoff events and floating-point underflow are kept distinct.
repo=fileparts(mfilename('fullpath'));
if nargin<1||isempty(source),source=fullfile(repo,'results','experiment_data.mat');end
if nargin<2||isempty(outDir),outDir=fullfile(repo,'reproduced_results','topology_diagnostics');end
if isstruct(source),R=source;else,S=load(source,'result');R=S.result;end
assert(isfield(R.proposed,'topologyEvents')&&isfield(R.untightened,'topologyEvents'), ...
    'Reproduce the topology example with its nonterminal event observer first.');
if ~isfolder(outDir),mkdir(outDir);end
P=R.P;F=reproduce_paper([],'diagnostic_helpers');
D=diagnose_tightening_margins(R,fullfile(outDir,'tightening'));
[T,tc]=analyze(P,R.proposed,R.auditProposed);
[U,uc]=analyze(P,R.untightened,R.auditUntightened);
E=F.localEntry(P,R.C,R.proposed);tol=1e-8;
q=R.auditUntightened;
dualViolation=max(0,-min(q.qpReference.lambdaStar,[],'all'));
untightKKT=q.allQPFeasible&&q.maxQPResidual<=tol&& ...
    q.maxQPStationarityResidual<=tol&&q.maxQPComplementarityResidual<=tol&&dualViolation<=tol;
checks=struct('naturalGeometricSwitch',~isempty(T.geometricBoundaryEvents), ...
    'bothGraphsConnectedAtSamples',T.minLambda2>0&&U.minLambda2>0, ...
    'tightenedSafetyAtSamples',all(T.minimumSafety>=0), ...
    'tighteningDiagnostics',D.summary.sampledChecksPass, ...
    'untightenedQPKKT',untightKKT, ...
    'targetStrictAndLocalAnalyticalConditions',R.C.targetMinReducedSlack>0&&R.C.localAnalyticConditions, ...
    'bothFinalErrorsBelow1eMinus6',T.finalError<1e-6&&U.finalError<1e-6, ...
    'originalLocalWindowAdmissible',E.summary.tailStart==850&&E.summary.tailEnd==1050&&E.summary.allLaterSavedSamplesAdmissible, ...
    'sensingBoundaryInequalityConditionalOnSpeedBound', ...
        R.auditProposed.safeActivationLHS>=R.auditProposed.safeActivationRHS);
V=struct('scope','trajectory-based numerical diagnostics', ...
    'tightened',T,'untightened',U,'tightening',D.summary, ...
    'localEntry',E.summary,'checks',checks,'allNumericalChecksPass',all(structfun(@(x)x,checks)), ...
    'untightenedMaxDualViolation',dualViolation,'KKTtolerance',tol, ...
    'regionalUniformCertificate',false,'continuousTimeRegionalCertificate',false, ...
    'unverifiedConditions',{D.summary.unverifiedConditions});
report=evalc('print_summary(V)');fprintf('%s',report);
fid=fopen(fullfile(outDir,'topology_summary.json'),'w');fprintf(fid,'%s\n',jsonencode(V,'PrettyPrint',true));fclose(fid);
fid=fopen(fullfile(outDir,'topology_summary.txt'),'w');fprintf(fid,'%s',report);fclose(fid);
writetable(tc,fullfile(outDir,'tightened_topology.csv'));
writetable(uc,fullfile(outDir,'untightened_topology.csv'));
end

function [A,curve]=analyze(P,S,Q)
nt=numel(S.t);Y=zeros(nt,P.N,P.n);
for i=1:P.N,j=(i-1)*P.N*P.n+P.n*(i-1)+(1:P.n);Y(:,i,:)=S.z(:,j);end
dist=zeros(nt,P.m);
for e=1:P.m,ij=P.edges(e,:);dist(:,e)=sqrt(sum((Y(:,ij(1),:)-Y(:,ij(2),:)).^2,3));end
support=dist<P.dc;W=zeros(size(dist));W(support)=exp(-dist(support).^2./(P.dc^2-dist(support).^2));
floating=W>0;events=S.topologyEvents;
if ~isempty(events)
    events=sortrows(events,[1,2]);keep=[true;abs(diff(events(:,1)))>1e-9|diff(events(:,2))~=0];events=events(keep,:);
end
transitions=zeros(0,6);
for e=1:P.m
    hit=find(diff(floating(:,e))~=0);
    for k=hit(:).',transitions(end+1,:)=[S.t(k),S.t(k+1),P.edges(e,:),floating(k,e),floating(k+1,e)];end %#ok<AGROW>
end
A=struct('samples',nt,'timeInterval',[S.t(1),S.t(end)], ...
    'edgeCountInitial',sum(support(1,:)),'edgeCountRange',[min(sum(support,2)),max(sum(support,2))], ...
    'floatingPointEdgeCountRange',[min(sum(floating,2)),max(sum(floating,2))], ...
    'geometricBoundaryEvents',events, ...
    'geometricEventColumns',{{'time','edgeIndex','outwardSign','radialSpeed','distanceRootResidual'}}, ...
    'edgeIndexPairs',P.edges,'floatingSupportChangeBrackets',transitions, ...
    'floatingChangeColumns',{{'timeLeft','timeRight','agentI','agentJ','oldSupport','newSupport'}}, ...
    'underflowEdgeSampleCount',nnz(support&~floating), ...
    'minLambda2',min(Q.lambda2),'minMatrixTreeMargin',min(Q.hTree), ...
    'minimumSafety',[min(Q.hInt),min(Q.hObs),min(Q.hTree)], ...
    'maxPairDistance',max(dist,[],'all'),'finalError',Q.finalError, ...
    'sampledPositionRegionContained',Q.regionContainmentSampled, ...
    'maxAgentSpeed',Q.maxAgentSpeedSampled,'maxInputNorm',Q.maxInputNormSampled);
curve=table(S.t,sum(support,2),sum(floating,2),Q.lambda2,Q.hTree, ...
    'VariableNames',{'time','geometric_edge_count','floating_edge_count','lambda2','matrix_tree_margin'});
end

function print_summary(V)
fprintf('\nTopology switching: trajectory-based numerical diagnostics\n');
fprintf('%-12s %9s %13s %13s %13s\n','Variant','Edges','min lambda2','min h_c','final error');
for key={'tightened','untightened'}
    A=V.(key{1});fprintf('%-12s %3d -> %d %13.7g %13.7g %13.7g\n',key{1},A.edgeCountInitial,A.edgeCountRange(2),A.minLambda2,A.minMatrixTreeMargin,A.finalError);
    for k=1:size(A.geometricBoundaryEvents,1)
        e=A.geometricBoundaryEvents(k,:);ij=A.edgeIndexPairs(e(2),:);
        fprintf('  Geometric edge (%d,%d): t=%.12g s, radial speed %.7g, root residual %.3g\n',ij,e(1),e(4),e(5));
    end
    for k=1:size(A.floatingSupportChangeBrackets,1)
        e=A.floatingSupportChangeBrackets(k,:);
        fprintf('  Floating support (%d,%d): %d -> %d in (%.12g, %.12g] s\n',e(3:6),e(1:2));
    end
end
fprintf('All numerical checks: %d. Uniform regional certificate: 0.\n',V.allNumericalChecksPass);
fprintf('Positive sampled margins and event localization do not certify all states or all times.\n');
end
