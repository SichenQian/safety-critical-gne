function summary = verify_reproduction(outDir)
%VERIFY_REPRODUCTION Recompute the paper example and compare archived data.
% Default output is reproduced_results/, preserving the reference results/.
repo=fileparts(mfilename('fullpath'));
if nargin<1||isempty(outDir),outDir=fullfile(repo,'reproduced_results');end
if ~isfolder(outDir),mkdir(outDir);end
reference=load(fullfile(repo,'results','experiment_data.mat'),'result');
logfile=fullfile(outDir,'reproduction_log.txt');
fid=fopen(logfile,'w');assert(fid>=0);fclose(fid);
diary(logfile);cleanup=onCleanup(@()diary('off')); %#ok<NASGU>
fprintf('Command: summary = verify_reproduction\nMATLAB %s\nPlatform %s\n',version,computer);
started=tic;
result=reproduce_paper(outDir);
comparison=compare_numeric_records(reference.result,result);
write_json(fullfile(outDir,'reference_comparison.json'),comparison);
assert(comparison.pass,'Recomputed numerical arrays differ from the archived reference.');
fig=jsondecode(fileread(fullfile(outDir,'figure_data_audit.json')));
assert(all(fig.safetyMinimaTightenedUntightened(:,1)>=0), 'Tightened sampled safety failed.');
assert(all(fig.safetyMinimaTightenedUntightened(:,2)<0), 'Expected ablation excursions missing.');
record=struct('parameters',result.P,'certificates',result.C, ...
    'solver',result.integrationSettings,'stateOrder', ...
    '1:50 local estimates; 51:60 velocities; 61:70 inputs; 71:95 slacks; 96:140 multipliers', ...
    'tightenedInitialState',result.proposed.z(1,:).', ...
    'untightenedInitialState',result.untightened.z(1,:).', ...
    'initialExtendedSafety',result.initialExtendedSafety, ...
    'figureDiagnostics',fig, ...
    'scope','Sampled regional safety diagnostics and analytical local bounds; no uniform regional safety certificate.');
write_full_precision(fullfile(outDir,'numerical_certificate.txt'),record);
write_json(fullfile(outDir,'initial_states.json'),struct( ...
    'stateOrder',record.stateOrder,'tightened',record.tightenedInitialState, ...
    'untightened',record.untightenedInitialState));
summary=struct('matlabVersion',version,'release',version('-release'),'platform',computer, ...
    'optimizationToolbox',ver('optim'),'fromScratch',true,'samplesPerVariant',numel(result.proposed.t), ...
    'stateDimension',size(result.proposed.z,2),'figureCount',7, ...
    'referenceNumericLeaves',comparison.numericLeaves,'referenceNumericValues',comparison.numericValues, ...
    'referenceNumericallyIdentical',comparison.numericallyIdentical, ...
    'referenceMaxAbsoluteDifference',comparison.maxAbsoluteDifference, ...
    'sampledSafetyMinima',fig.safetyMinimaTightenedUntightened, ...
    'localErrorInterval',[fig.entry.tailStart,fig.entry.tailEnd], ...
    'continuousTimeRegionalCertificate',false,'wallSeconds',toc(started),'status','VERIFICATION_PASS');
write_json(fullfile(outDir,'verification_summary.json'),summary);
fprintf('VERIFICATION_PASS: %d values checked; maximum absolute difference %.17g\n', ...
    comparison.numericValues,comparison.maxAbsoluteDifference);
end

function write_json(path,data)
fid=fopen(path,'w');assert(fid>=0);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(data,'PrettyPrint',true));
end
