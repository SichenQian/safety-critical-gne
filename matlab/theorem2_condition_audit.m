function report=theorem2_condition_audit(outputFolder,dataRoot)
%THEOREM2_CONDITION_AUDIT Separate design checks, observations and hypotheses.
% With no arguments, recompute the compact report from archived diagnostics.
% Specify an output folder to write JSON and four-column condition tables.
repo=fileparts(fileparts(mfilename('fullpath')));
if nargin<1,outputFolder='';end
if nargin<2||isempty(dataRoot),dataRoot=repo;end
if isfolder(fullfile(dataRoot,'reference')),prefix='reference';else,prefix='results';end
P=design_parameters();C=theorem_certificates(P);
aInt=2*P.regionDiameter;
corners=[P.regionBox(1,[1 1 2 2]);P.regionBox(2,[1 2 1 2])].';aObs=0;
for k=1:P.nObs,aObs=max(aObs,2*max(vecnorm(corners-P.obs(k,:),2,2)));end
aC=C.Gh;lhs=[sqrt(2)*aInt*P.trackingBudget,aObs*P.trackingBudget,...
 sqrt(P.N)*aC*P.trackingBudget+P.connMismatchBudget];
limits=[P.DeltaInt P.DeltaObs P.DeltaC];
design=struct('coefficients',[aInt aObs aC],'trackingBudget',P.trackingBudget,...
 'connectivityDiscrepancyBudget',P.connMismatchBudget,'inputBallRadius',P.auditInputRadius,...
 'requiredTightening',lhs,'selectedTightening',limits,'remainingMargins',limits-lhs,...
 'activationLHS',2*P.dc*(2*P.regionSpeedMax),...
 'activationRHS',P.alpha1*(P.dc^2-P.dsafe^2),...
 'classification','Analytic coefficient formulas and sufficient inequalities evaluated in double precision.');
assert(all(lhs<=limits)&&design.activationLHS<=design.activationRHS);
observations=struct();
for name={'selected','selected_refined'}
 n=name{1};folder=fullfile(dataRoot,prefix,n);
 R=jsondecode(fileread(fullfile(folder,'final_full.json')));
 K=jsondecode(fileread(fullfile(folder,'refined_peaks.json')));
 region=jsondecode(fileread(fullfile(folder,'region_check.json')));
 V=struct('trackingPeak',max([R.maxTracking;K.tracking(:,2)]),...
  'inputBallDiscrepancyPeak',max([R.maxDeltaBall;K.deltaBall(:,2)]),...
  'actualInputDiscrepancyPeak',R.maxDeltaActual,...
  'inputNormPeakAtAuditedStates',R.maxInputNorm,...
  'optimizerInputNormPeakAtAuditedStates',R.maxOptimizerInputNorm,...
  'auditedStates',R.samples,'validReferenceQPs',R.validQP,...
  'kktResidualMaxima',R.maxKKT,'maximumKKTComponent',max(R.maxKKT),...
  'referenceKKTCoordinates',R.KKTcoordinates,...
  'physicalDomainResidenceAtCheckedStates',region.trajectoryWithinRegion,...
  'physicalDomainDiagnostics',region,'originalECBFResidualMaxima',R.maxECBF);
 assert(V.trackingPeak<P.trackingBudget&&V.inputBallDiscrepancyPeak<P.connMismatchBudget);
 assert(V.inputNormPeakAtAuditedStates<=P.auditInputRadius&&V.optimizerInputNormPeakAtAuditedStates<=P.auditInputRadius);
 assert(V.validReferenceQPs==V.auditedStates&&V.maximumKKTComponent<1e-8);
 assert(V.physicalDomainResidenceAtCheckedStates&&all(V.originalECBFResidualMaxima<=0));
 observations.(n)=V;
end
S=observations.selected;F=observations.selected_refined;
hypotheses=struct('regionalUniformConnectivityDiscrepancyCertified',false,...
 'fullSlowDomainForwardInvarianceCertified',false,'regionWideQPFeasibilityCertified',false,...
 'continuousTimeUniformTrackingBoundCertified',false,...
 'continuousTimeInputMembershipCertified',false);
rows={...
 'Collision tightening','sqrt(2) a_int r_u <= 0.5',num(lhs(1)),...
 'Analytic coefficient bound; sufficient inequality evaluated in double precision';...
 'Obstacle tightening','a_obs r_u <= 0.7',num(lhs(2)),...
 'Analytic coefficient bound; sufficient inequality evaluated in double precision';...
 'Connectivity tightening','sqrt(5) a_c r_u + delta_c <= 0.4',num(lhs(3)),...
 'Analytic coefficient bound; sufficient inequality evaluated in double precision';...
 'Tracking peak on tightened trajectory','< r_u = 0.061',num(S.trackingPeak),...
 'Recorded tightened-trajectory mesh/dense/interpolant diagnostics';...
 'Input-ball connectivity-discrepancy peak','< delta_c = 0.03',num(S.inputBallDiscrepancyPeak),...
 'At each tightened-trajectory state maximize over ||u|| <= 15; not over Theta_R';...
 'Regional uniform connectivity discrepancy',...
 'sup over Theta_R x U_R of |q_c - sum_i qhat_i_c| <= delta_c',...
 'Retained assumption', 'Not certified over the region; trajectory peak does not replace this bound';...
 'Input-set membership','u(t) in U_R; U_R = {u: ||u|| <= 15}',num(S.inputNormPeakAtAuditedStates),...
 'Input-norm peak at audited tightened-trajectory states; not a continuous-time certificate';...
 'Full slow-domain residence','vartheta(t) in Theta_R','Retained assumption',...
 'Full Theta_R forward invariance not established by physical D_R trajectory checks';...
 'Region-wide QP feasibility','QP feasible for every vartheta in Theta_R','Retained assumption',...
 'Pointwise reference-QP checks do not establish feasibility throughout Theta_R';...
 'Continuous-time uniform tracking bound','||u(t)-uhat_xi_star(vartheta(t))|| <= r_u',...
 'Retained assumption','Finite trajectory diagnostics do not certify a uniform continuous-time bound';...
 'Physical-domain residence','Position box; diameter <= 2.5; individual speed <= 0.5',...
 'Observed at checked states','Physical D_R check only; distinct from full slow-domain Theta_R invariance';...
 'Pointwise reference-QP checks','All audited states valid',sprintf('%d/%d',S.validReferenceQPs,S.auditedStates),...
 'Numerical reference solves and KKT diagnostics at recorded trajectory states';...
 'Reference-QP KKT residual','Diagnostic maximum of four saved coordinates',num(S.maximumKKTComponent),...
 'Solver accuracy; not filter tracking error or region-wide QP feasibility';...
 'Original physical ECBF residuals','q_int, q_obs, q_c <= 0',...
 sprintf('%.12g; %.12g; %.12g',S.originalECBFResidualMaxima),...
 'Recorded tightened-trajectory states; collision residuals apply to active rows';...
 'Sensing-edge reactivation','2 d_c v_pair <= alpha1 (d_c^2-dsafe^2)',...
 sprintf('%.12g <= %.12g',design.activationLHS,design.activationRHS),...
 'Analytic sufficient inequality on the declared physical domain'};
report=struct('schemaVersion',1,'design',design,'observations',observations,...
 'precisionComparison',struct('trackingPeakDifference',abs(S.trackingPeak-F.trackingPeak),...
 'inputBallDiscrepancyPeakDifference',abs(S.inputBallDiscrepancyPeak-F.inputBallDiscrepancyPeak)),...
 'hypotheses',hypotheses,'conditions',{rows},...
 'kktCoordinateOrder',{{'primal','stationarity','complementarity','dual'}},...
 'trackingErrorDefinition','u - uhat_xi_star(vartheta); distinct from reference-solver KKT residuals.',...
 'connectivityDiscrepancyDefinition',...
 'delta_c_tr(t) = |db(vartheta(t))| + 15 ||da(vartheta(t))||_2, a maximization over the input ball at a fixed trajectory state.',...
 'physicalVsSlowDomain','D_R concerns physical positions and velocities; Theta_R additionally concerns decision estimates.',...
 'regionalUniformCertificate',false,'continuousTimeProof',false);
report.conditions=cell2struct(rows,{'condition','requiredBound','numericalValue','verification'},2);
if ~isempty(outputFolder)
 if ~exist(outputFolder,'dir'),mkdir(outputFolder);end
 write_json(fullfile(outputFolder,'theorem2_audit.json'),report);
 names={'Condition','Required bound','Numerical value','Verification'};
 writetable(cell2table(rows,'VariableNames',names),fullfile(outputFolder,'theorem2_conditions_with_scope.csv'));
 nominalFile=fullfile(dataRoot,'verification','nominal_hb.json');
 if ~isfile(nominalFile),nominalFile=fullfile(repo,'verification','nominal_hb.json');end
 N=jsondecode(fileread(nominalFile));
 I=jsondecode(fileread(fullfile(dataRoot,prefix,'local','initial.json')));
 other={...
  'Theorem 1 gains',sprintf('c>%.12g; gamma>%.12g',C.cLower,C.gammaLower),...
   sprintf('c=%.12g; gamma=%.12g',P.c,P.gamma),'Analytic sufficient inequalities evaluated in double precision';...
  'Theorem 1 nominal-flow connectivity','> 0.04',num(N.standard.minimumLambda2),...
   'Independent nominal HB trajectory; accepted mesh and dense/interpolant diagnostics with a precision repeat'};
 local={...
  'Theorem 3 epsilon',['< ' num(C.epsUpper)],num(P.epsilon),'Explicit local sufficient inequalities evaluated in double precision';...
  'Local slow initialization',['< ' num(C.rTheta1)],num(I.eTheta),'Explicit local certificate and numerical initialization check';...
  'Local fast initialization',['< ' num(C.rFast)],num(I.eFast),'Explicit local certificate and numerical initialization check';...
  'Local Vc initialization',['< ' num(C.rho)],num(I.Vc),'Explicit local certificate and numerical initialization check';...
  'Omitted-pair multipliers','Rows 15/16 initialized at zero','0; retained at zero in saved output','Full projected flow; no controller equations omitted'};
 writetable(cell2table([other;rows;local],'VariableNames',names),fullfile(outputFolder,'theorem_checks_with_scope.csv'));
end
fprintf('THEOREM2_CONDITION_AUDIT_PASS: design and recorded-trajectory checks; regional hypotheses remain assumptions.\n');
end

