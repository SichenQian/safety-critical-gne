function build_final_tables()
root=paper_data_root();tab=fullfile(root,'tables');man=fullfile(root,'manuscript');
D=load(fullfile(root,'results','selected','trajectory.mat'),'P');P=D.P;C=theorem_certificates(P);L=load(fullfile(root,'results','local','trajectory.mat'),'initial');
Q=struct();
nominalFile=fullfile(root,'verification','nominal_hb.json');
if ~isfile(nominalFile)
 repo=fileparts(fileparts(mfilename('fullpath')));nominalFile=fullfile(repo,'verification','nominal_hb.json');
end
N=jsondecode(fileread(nominalFile));
assert(N.parameters.c==P.c&&N.parameters.gamma==P.gamma&&N.parameters.dc==P.dc);
assert(isequal(N.parameters.y0,P.y0)&&isequal(N.parameters.v0,P.v0));
Q.nominal=N.standard;Q.nominalRefined=N.refined;
aInt=2*P.regionDiameter;corners=[P.regionBox(1,[1 1 2 2]);P.regionBox(2,[1 2 1 2])].';aObs=0;
for o=1:P.nObs,aObs=max(aObs,2*max(vecnorm(corners-P.obs(o,:),2,2)));end
Q.barAInt=aInt;Q.barAObs=aObs;Q.barAC=C.Gh;Q.designLHS=[sqrt(2)*aInt*P.trackingBudget,aObs*P.trackingBudget,sqrt(5)*C.Gh*P.trackingBudget+P.connMismatchBudget];Q.designMargins=[P.DeltaInt P.DeltaObs P.DeltaC]-Q.designLHS;
Q.gainCLower=C.cLower;Q.gainGammaLower=C.gammaLower;Q.tildeL=C.tildeL;Q.local=L.initial;Q.localConstants=C;Q.localFits=jsondecode(fileread(fullfile(tab,'local_fits.json')));
names={'selected','selected_refined','untightened','untightened_refined'};
for k=1:4
 name=names{k};folder=fullfile(root,'results',name);F=jsondecode(fileread(fullfile(folder,'final_full.json')));peaks=jsondecode(fileread(fullfile(folder,'refined_peaks.json')));
 V=struct('summary',F,'geometry',jsondecode(fileread(fullfile(folder,'geometry_extrema.json'))),...
 'graph',jsondecode(fileread(fullfile(folder,'graph_statistics.json'))),'region',jsondecode(fileread(fullfile(folder,'region_check.json'))),...
 'trackingPeak',max([F.maxTracking;peaks.tracking(:,2)]),'deltaPeak',max([F.maxDeltaBall;peaks.deltaBall(:,2)]));
 Q.(name)=V;
end
Q.trackingDense=Q.selected.trackingPeak;Q.deltaDense=Q.selected.deltaPeak;Q.trackingRefined=Q.selected_refined.trackingPeak;Q.deltaRefined=Q.selected_refined.deltaPeak;
Q.trackingPeakDifference=abs(Q.trackingDense-Q.trackingRefined);Q.deltaPeakDifference=abs(Q.deltaDense-Q.deltaRefined);
Q.baseline=Q.selected.summary;Q.refined=Q.selected_refined.summary;
write_json(fullfile(tab,'final_numbers.json'),Q);
% Keep numerical relations separate from the regional assumptions in the theorem.
cond={...
 'Theorem 1: c',sprintf('%.9g',P.c),sprintf('> %.9g',C.cLower);...
 'Theorem 1: gamma',sprintf('%.9g',P.gamma),sprintf('> %.9g',C.gammaLower);...
 'Nominal flow minimum lambda2',sprintf('%.9g',Q.nominal.minimumLambda2),sprintf('> %.9g',P.lambdaLower);...
 'Theorem 2: sqrt(2) a_int r_u',sprintf('%.9g',Q.designLHS(1)),sprintf('< DeltaInt = %.9g',P.DeltaInt);...
 'Theorem 2: a_obs r_u',sprintf('%.9g',Q.designLHS(2)),sprintf('< DeltaObs = %.9g',P.DeltaObs);...
 'Theorem 2: sqrt(5) a_c r_u + delta_c',sprintf('%.9g',Q.designLHS(3)),sprintf('< DeltaC = %.9g',P.DeltaC);...
 'Trajectory maximum tracking error',sprintf('%.9g',Q.trackingDense),sprintf('< r_u = %.9g',P.trackingBudget);...
 'Trajectory maximum input-ball discrepancy',sprintf('%.9g',Q.deltaDense),sprintf('< delta_c = %.9g',P.connMismatchBudget);...
 'Trajectory maximum applied input norm',sprintf('%.9g',Q.baseline.maxInputNorm),sprintf('<= %.9g',P.auditInputRadius);...
 'Theorem 3: epsilon',sprintf('%.9g',P.epsilon),sprintf('< epsilon_bar = %.9g',C.epsUpper);...
 'Theorem 3: initial slow error',sprintf('%.9g',L.initial.eTheta),sprintf('< r_Theta1 = %.9g',C.rTheta1);...
 'Theorem 3: initial fast error',sprintf('%.9g',L.initial.eFast),sprintf('< r_f = %.9g',C.rFast);...
 'Theorem 3: initial Vc',sprintf('%.9g',L.initial.Vc),sprintf('< rho_c = %.9g',C.rho)};
writetable(cell2table(cond,'VariableNames',{'Condition','Numerical_value','Required_inequality'}),fullfile(tab,'theorem2_conditions.csv'));
f=fopen(fullfile(man,'condition_table.tex'),'w');
fprintf(f,'\\begin{tabular}{@{}lcc@{}}\n\\hline\nCondition & Numerical value & Required inequality\\\\\\hline\n');
rows={...
 '$c$',P.c,sprintf('$> %s$',texnum(C.cLower));...
 '$\gamma$',P.gamma,sprintf('$> %s$',texnum(C.gammaLower));...
 '$\min_t\lambda_2$ (nominal)',Q.nominal.minimumLambda2,'$>0.04$';...
 '$\sqrt2\bar a_{\rm int}r_u$',Q.designLHS(1),['$<\Delta^{\rm int}=' texnum(P.DeltaInt) '$'];...
 '$\bar a_{\rm obs}r_u$',Q.designLHS(2),['$<\Delta^{\rm obs}=' texnum(P.DeltaObs) '$'];...
 '$\sqrt5\bar a_c r_u+\delta_c$',Q.designLHS(3),['$<\Delta^{\rm c}=' texnum(P.DeltaC) '$'];...
 '$\max_t\|\widetilde u\|$',Q.trackingDense,['$<r_u=' texnum(P.trackingBudget) '$'];...
 '$\max_t\delta_c(t)$',Q.deltaDense,['$<\delta_c=' texnum(P.connMismatchBudget) '$'];...
 '$\max_t\|u(t)\|$',Q.baseline.maxInputNorm,['$\leq' texnum(P.auditInputRadius) '$'];...
 '$\epsilon$',P.epsilon,['$<\bar\epsilon=' texnum(C.epsUpper) '$'];...
 '$\|e_\vartheta(0)\|$',L.initial.eTheta,['$<r_{\Theta_1}=' texnum(C.rTheta1) '$'];...
 '$\|e_f(0)\|$',L.initial.eFast,sprintf('$<r_f=%s$',texnum(C.rFast));...
 '$V_c(0)$',L.initial.Vc,['$<\rho_c=' texnum(C.rho) '$']};
for k=1:size(rows,1)
 if k==1,fprintf(f,'\\multicolumn{3}{c}{Theorem~1 and graph connectivity}\\\\\n');elseif k==4,fprintf(f,'\\hline\\multicolumn{3}{c}{Theorem~2: design budgets and trajectory errors}\\\\\n');elseif k==10,fprintf(f,'\\hline\\multicolumn{3}{c}{Theorem~3: local initialization}\\\\\n');end
 fprintf(f,'%s & $%s$ & %s\\\\\n',rows{k,1},texnum(rows{k,2}),rows{k,3});
end
fprintf(f,'\\hline\n\\end{tabular}\n');fclose(f);
vals={'GainC',C.cLower;'GainGamma',C.gammaLower;'TildeL',C.tildeL;'TrackPeak',Q.trackingDense;'DeltaPeak',Q.deltaDense;'LambdaMin',Q.nominal.minimumLambda2;...
 'HIntMin',Q.selected.geometry.collision.h;'HObsMin',Q.selected.geometry.obstacle.h;'HCMin',Q.selected.geometry.tree.h;'SlowInitial',L.initial.eTheta;...
 'FastInitial',L.initial.eFast;'SlowRadius',C.rTheta1;'FastRadius',C.rFast;'SlowFit',Q.localFits.slowSlope;'FastFit',Q.localFits.fastSlope;...
 'SwitchOn',Q.baseline.crossings(1,1);'SwitchOff',Q.baseline.crossings(2,1);...
 'UIntMin',Q.untightened.geometry.collision.h;'UObsMin',Q.untightened.geometry.obstacle.h;'UCMin',Q.untightened.geometry.tree.h;...
 'ULambdaMin',Q.untightened.summary.minimumLambda2;'TreeTMin',Q.selected.graph.minimumBottleneckTreeWeight;'TreeUMin',Q.untightened.graph.minimumBottleneckTreeWeight};
f=fopen(fullfile(man,'numerical_values.tex'),'w');for k=1:size(vals,1),fprintf(f,'\\newcommand{\\%s}{%s}\n',vals{k,1},texnum(vals{k,2}));end;fclose(f);
% Side-by-side full-horizon results, without changing baseline diagnostics.
metrics={'minimum_collision_h','minimum_obstacle_h','minimum_tree_h','minimum_lambda2','maximum_components','minimum_active_weight_computed','minimum_bottleneck_tree_weight','maximum_tracking_error','maximum_input_ball_discrepancy','maximum_KKT_residual'};
numbers=zeros(numel(metrics),4);
for k=1:4,V=Q.(names{k});numbers(:,k)=[V.geometry.collision.h;V.geometry.obstacle.h;V.geometry.tree.h;V.summary.minimumLambda2;V.graph.maxComponents;V.graph.minimumActiveWeightComputed;V.graph.minimumBottleneckTreeWeight;V.trackingPeak;V.deltaPeak;max(V.summary.maxKKT)];end
writetable([table(metrics.','VariableNames',{'Metric'}),array2table(numbers,'VariableNames',names)],fullfile(tab,'tightened_untightened.csv'));
assert(all(Q.designMargins>0));theorem2_condition_audit(tab,root);fprintf('FINAL_TABLES_DONE\n');
end
function s=texnum(x)
s=sprintf('%.6g',x);tok=regexp(s,'^(.*)e([+-]?\d+)$','tokens','once');if ~isempty(tok),s=sprintf('%s\\times10^{%d}',tok{1},str2double(tok{2}));end
end
